--
-- Раньше отсечкой служило само состояние тарифа: триал давали, если
-- plan='free' AND plan_expires IS NULL, то есть «PRO не было никогда».
-- Из-за этого человек, у которого PRO когда-то был и истёк (старый триал,
-- ручная выдача, разовая акция), при первом запуске бота оставался ни с чем.
--
-- Отдельная колонка разводит два разных вопроса: «есть ли PRO сейчас» и
-- «выдавали ли приветственный триал». Бэкфилл намеренно не делается — те, кто
-- получал триал до этой миграции, при следующем /start получат 7 дней ещё раз,
-- по одному разу на человека. Дальше колонка закрывает повтор навсегда.

